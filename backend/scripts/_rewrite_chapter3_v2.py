from docx import Document

src = r"C:\Users\zhu20\Desktop\毕业论文\毕设论文参考模板2026_电影购票系统_完成版.docx"
out = r"C:\Users\zhu20\Desktop\毕业论文\毕设论文参考模板2026_电影购票系统_完成版_v2.docx"
doc = Document(src)

start = -1
end = -1
for i, p in enumerate(doc.paragraphs):
    t = (p.text or '').strip()
    if t.startswith('第3章') and '需求分析' in t:
        start = i
    if start != -1 and t.startswith('第4章'):
        end = i
        break
if start == -1:
    raise SystemExit('未找到第3章')
if end == -1:
    end = len(doc.paragraphs)

chapter3 = [
"第3章 系统需求分析",
"3.1 需求分析目标",
"需求分析的目标是明确系统边界、角色分工与核心业务流程，为后续系统设计和编码实现提供可验证依据。针对本课题，需求分析重点围绕“用户如何高效完成购票”和“平台如何稳定管理订单与座位”两条主线展开。",
"3.2 角色与业务场景",
"系统主要包含三类角色：普通用户、管理员、系统运维人员。普通用户关注电影信息检索、场次选择与订单处理；管理员关注电影上下架、用户管理和数据统计；运维人员关注电影数据导入、排期重建和服务可用性。",
"3.3 用户端功能需求",
"3.3.1 账号与登录需求",
"用户可通过小程序进入系统并完成登录。系统需支持保存登录态、退出登录、用户信息读取与更新。未登录用户可浏览电影和影院，但在收藏、评论、下单等敏感操作时应进行登录拦截。",
"3.3.2 电影浏览与检索需求",
"系统需支持“正在热映”“即将上映”两类电影列表展示，支持按关键词检索电影，支持进入电影详情页查看海报、评分、类型、主演、剧情简介等信息。电影数据应支持后端批量更新，避免长期使用静态演示数据。",
"3.3.3 影院与场次查询需求",
"用户可按城市或关键词筛选影院，并查看影院详情页中的可选场次。系统应支持按日期筛选场次，必要时根据电影维度过滤场次结果。场次信息至少包含放映时间、影厅类型、票价、剩余座位等关键字段。",
"3.3.4 选座与下单需求",
"用户在选座页可视化查看座位状态（可选、已锁定、已售出），选择座位后提交订单。系统必须校验座位有效性与价格合法性，防止非法请求或重复提交。下单成功后应生成唯一订单号并记录订单创建时间。",
"3.3.5 订单流转需求",
"订单需支持完整生命周期管理：待支付、已支付、已取消、已退款。待支付订单支持取消；已支付订单在规则允许范围内可发起退款；已取消/已退款订单支持删除。订单详情页应展示电影、影院、场次、座位、金额与状态等信息。",
"3.3.6 用户互动需求",
"系统需支持电影收藏、取消收藏、发表评论、查看评论列表。收藏和评论与用户身份绑定，防止匿名写入；评论需做文本非空与长度校验，保证内容可展示性。",
"3.4 管理端功能需求",
"3.4.1 电影管理需求",
"管理员可查看电影列表，执行上下架状态更新、删除电影、单片信息补全等操作。删除电影时系统应联动清理该电影关联的场次、座位、评论和收藏数据，避免脏数据残留。",
"3.4.2 用户与统计需求",
"管理员可查看用户列表与关键统计指标（如今日订单量、待处理订单数等），为运营分析提供数据支持。统计接口应具备权限校验，禁止普通用户访问。",
"3.4.3 排期与数据运维需求",
"管理员或运维人员可触发排期重建、TMDB 批量导入、上映状态重算等维护操作。系统应提供脚本化工具和接口化能力，支持开发环境快速重建演示数据。",
"3.5 数据需求分析",
"系统核心数据实体包括：用户（users）、电影（movies）、影院（cinemas）、场次（schedules）、座位（seats）、订单（orders）、评论（movie_comments）、收藏（collections）。其中 movieId、cinemaId、scheduleId、orderId 是关键关联字段；座位状态与订单状态是业务一致性控制的核心数据。",
"3.6 业务流程需求分析",
"3.6.1 购票主流程",
"用户进入电影详情页后选择购票，跳转影院列表并选择影院；在影院详情页选择日期和场次后进入选座页；确认座位后提交订单；支付成功后完成购票。",
"3.6.2 取消与退款流程",
"待支付订单可主动取消，系统需释放已锁座位；已支付订单发起退款后，系统将订单状态更新为已退款并回滚座位状态。",
"3.6.3 失败与异常流程",
"当出现座位冲突、参数非法、网络异常等情况时，系统应返回明确错误信息并保持数据库一致状态，不得出现“订单失败但座位已售出”或“订单成功但无座位记录”等异常。",
"3.7 非功能需求分析",
"3.7.1 性能需求：核心接口应在可接受时间内响应，列表查询需具备分页能力。",
"3.7.2 可靠性需求：通过事务机制确保订单与座位状态一致，通过异常处理提升可诊断性。",
"3.7.3 安全性需求：接口需校验用户身份与管理员权限，关键参数需服务端二次校验。",
"3.7.4 可维护性需求：前后端分层明确，统一 API 封装，便于扩展与故障定位。",
"3.8 本章小结",
"本章从角色、功能、数据、流程及非功能五个维度完成了需求分析，明确了在线电影购票系统的建设目标与实现约束，为第4章系统设计提供了完整依据。"
]

for i, line in enumerate(chapter3):
    idx = start + i
    if idx < len(doc.paragraphs):
        doc.paragraphs[idx].text = line
    else:
        doc.add_paragraph(line)

used_end = start + len(chapter3)
for idx in range(used_end, end):
    doc.paragraphs[idx].text = ''

doc.save(out)
print(out)
print('start=', start, 'end=', end, 'written=', len(chapter3))
